namespace lab {

// DES-ядро: дискретно-событийный планировщик с ОДНИМ оператором и стендами как
// разделяемыми ресурсами (задача об интерференции машин). Каждая операция проходит
// три фазы: настройка (оператор) → автономный прогон (стенд) → снятие (оператор).
// Пока стенд автономно прогоняет программу, оператор уходит обслуживать другие стенды
// — это даёт реалистичный T_cycle (makespan) с перекрытием работ.
//
// Порядок постановки операций берётся из TestRoute (его формирует RoutePlanner:
// по образцам / по операциям). Приоритеты оператора: сперва снять завершившийся
// прогон (освободить стенд), иначе — начать настройку следующей операции; если
// нужный стенд занят незавершённым прогоном — дождаться и снять его.
class Scheduler {
public:
    [[nodiscard]] Schedule build(const ProblemDefinition& problem, const TestRoute& order) const;
};

}  // namespace lab
