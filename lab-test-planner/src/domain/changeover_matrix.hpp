namespace lab {

// Матрица переналадки A→B на универсальном осевом-крутильном стенде (e_axial_torsion).
//
// Растяжение, кручение и совмещённое растяжение+кручение выполняет ОДНА машина,
// поэтому переход между программами требует реальной переналадки, а её
// длительность и энергия зависят от ПАРЫ (предыдущая программа → следующая):
//   - диагональ (та же программа) = только смена образца (захваты сохраняются);
//   - растяжение↔кручение         = смена захватов/оснастки (дорого);
//   - переходы с/на совмещённое   = частичная переналадка (средняя цена).
//
// Это даёт рычаг себестоимости C: группировка одинаковых программ снижает
// суммарное время и энергию переналадок (статья C_setup / C_energy_setup).

// Принадлежит ли операция набору универсального стенда {растяжение, кручение,
// растяжение+кручение}.
[[nodiscard]] bool isUniversalStandOperation(TestOperationType type);

// Время переналадки перехода from→to на универсальном стенде, мин.
// Для операций вне набора возвращает базовое значение смены образца.
[[nodiscard]] double changeoverTimeMin(TestOperationType from, TestOperationType to);

}  // namespace lab
